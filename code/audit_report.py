"""One-command audit report for any compatible activity log.

    python3 audit_report.py --csv examples/example_log.csv          # a log in the documented format
    python3 audit_report.py --specimens diffenv_results/balanced_2026-10-17/specimens
    python3 audit_report.py --specimens <dir> --out report.md       # also write the report to a file

No API key, no network. Writes a Markdown report to stdout (and to --out).

LOG FORMAT (CSV, one row per action; header required)
    run        any identifier of an independent run, group or organization
    time       integer time step (round, day, ...)
    member     member identifier
    action     "work" (a task action) or "tell" (a directed interaction); other actions are ignored
    partner    recipient of a "tell"; empty for "work"
    task_type  type of the task worked; empty for "tell"
  optional:
    opportunity  1 if the member had something to work on at this time step, else 0
                 (rows with action "opp"; enables the opportunity-adjusted individual measure)

WHAT THE REPORT COMPUTES, per run, each against its own label-permutation baseline
(95th percentile of 200 draws that shuffle member labels within each window):
    individual  work per window (or per opportunity, if supplied)
    functional  favoured-type repeatability: is the type a member favours stable over windows?
    relational  partner consistency: overlap of a member's partners in consecutive windows
    structural  hub persistence: repeatability of interactions received per window
and, across runs: the count of runs above baseline (about 5% expected by chance), the median
with a bootstrap 95% interval, and whether the same member holds the top structural position
in every run (a signature of prescribed or label-induced structure when member identities are
comparable across runs).

WHAT IT CANNOT ESTABLISH ON ITS OWN
    Persistence is not provenance. A log shows whether differences persist beyond chance; whether
    they were prescribed, induced by the design or generated by the members' own histories needs
    the controlled contrasts described in the technical appendix (shuffled labels, wiped
    histories, cut communication, reassigned roles), i.e. logs from those conditions.
"""
from __future__ import annotations

import argparse, csv, glob, itertools, json, os, sys
from collections import Counter, defaultdict

import numpy as np

from diffenv.measures import differentiation, specialization, partner_consistency


def _avg_ranks(x):
    x = np.asarray(x, dtype=float); order = np.argsort(x, kind="mergesort"); r = np.empty(len(x))
    r[order] = np.arange(1, len(x) + 1)
    for v in np.unique(x):
        idx = x == v
        r[idx] = r[idx].mean()
    return r


def _spearman(x, y):
    """Spearman correlation with average ranks for ties (stable across numpy versions)."""
    if len(x) < 3:
        return float("nan")
    rx, ry = _avg_ranks(x), _avg_ranks(y)
    if rx.std() == 0 or ry.std() == 0:
        return float("nan")
    return float(np.corrcoef(rx, ry)[0, 1])

N_DRAWS = 200


def runs_from_csv(path, window):
    rows = list(csv.DictReader(open(path, newline="")))
    by_run = defaultdict(list)
    for r in rows:
        by_run[r["run"]].append(r)
    out = {}
    for run, rs in by_run.items():
        members = sorted({r["member"] for r in rs} | {r["partner"] for r in rs if r.get("partner")})
        t0 = min(int(r["time"]) for r in rs); T = max(int(r["time"]) for r in rs) - t0 + 1
        log, opp = [], {}
        for r in rs:
            t = int(r["time"]) - t0
            if r["action"] == "opp":
                opp[(r["member"], t)] = int(r.get("opportunity") or 1)
            else:
                log.append({"round": t, "window": t // window, "sender": r["member"], "mtype": r["action"],
                            "recipient": r.get("partner") or None, "payload": {"type": r.get("task_type") or None}})
        out[run] = {"log": log, "agents": members, "n_windows": T // window, "window": window, "opportunity": opp or None}
    return out


def runs_from_specimens(paths):
    out = {}
    for p in paths:
        d = json.load(open(p)); W = d["config"]["window"]
        opp = {}
        for k, v in (d.get("opportunity") or {}).items():
            a, r = k.split("|"); opp[(a, int(r))] = v
        out[os.path.basename(p).replace(".json", "")] = {
            "log": d["log"], "agents": d["agents"], "n_windows": d["config"]["rounds"] // W, "window": W,
            "opportunity": opp or None}
    return out


def audit_run(run):
    log, ag, nW, W, opp = run["log"], run["agents"], run["n_windows"], run["window"], run["opportunity"]
    work = defaultdict(int); rec = defaultdict(int); types = defaultdict(Counter); partners = defaultdict(set)
    for m in log:
        w = m["window"]
        if w >= nW:
            continue
        if m["mtype"] == "work":
            work[(m["sender"], w)] += 1
            if m["payload"].get("type"):
                types[(m["sender"], w)][m["payload"]["type"]] += 1
        elif m["mtype"] == "tell":
            rec[(m["recipient"], w)] += 1
            partners[(m["sender"], w)].add(m["recipient"]); partners[(m["recipient"], w)].add(m["sender"])
    indiv, hub = [], []
    for w in range(nW):
        for a in ag:
            hub.append(("r", w, a, rec[(a, w)]))
            if opp:
                o = sum(1 for t in range(w * W, (w + 1) * W) if opp.get((a, t), 0) > 0)
                if o:
                    indiv.append(("r", w, a, work[(a, w)] / o))
            else:
                indiv.append(("r", w, a, work[(a, w)]))
    n_types = len({t for c in types.values() for t in c}) or 1
    tc = {(a, w): dict(types[(a, w)]) for w in range(nW) for a in ag}
    ps = {(a, w): set(partners[(a, w)]) for w in range(nW) for a in ag}
    res = {}
    R = differentiation(indiv, n_draws=N_DRAWS)["R"]; res["individual"] = (R["observed"], R["null_p95"])
    fav = specialization(tc, n_types, n_draws=N_DRAWS)["favoured_type_R"]
    res["functional"] = (fav.get("observed", float("nan")), fav.get("null_p95", float("nan")))
    pc = partner_consistency(ps, ag, nW, n_draws=N_DRAWS); res["relational"] = (pc["observed"], pc.get("null_p95", float("nan")))
    R = differentiation(hub, n_draws=N_DRAWS)["R"]; res["structural"] = (R["observed"], R["null_p95"])
    totals = Counter({a: sum(rec[(a, w)] for w in range(nW)) for a in ag})
    res["_top"] = totals.most_common(1)[0][0] if sum(totals.values()) else None
    res["_received"] = [totals[a] for a in ag]
    return res


def boot_ci(v, n=10000, seed=1):
    v = np.asarray([x for x in v if not np.isnan(x)])
    if len(v) < 2:
        return float("nan"), float("nan")
    m = np.median(np.random.default_rng(seed).choice(v, size=(n, len(v))), axis=1)
    return float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


DIMS = ("individual", "functional", "relational", "structural")


def report(runs, source):
    res = {k: audit_run(v) for k, v in runs.items()}
    L = [f"# Emergence audit report", "", f"Source: `{source}`  ", f"Runs: {len(res)}; label-permutation baseline: "
         f"95th percentile of {N_DRAWS} draws per run and dimension.", "",
         "## Step 1. Detect: persistence against each run's own baseline", "",
         "Each cell is observed persistence / baseline; **bold** = above baseline.", "",
         "| run | " + " | ".join(DIMS) + " | top receiver |", "|---|" + "---|" * (len(DIMS) + 1)]
    fmt = lambda o, b: ("n/a" if np.isnan(o) else (f"**{o:.2f}** / {b:.2f}" if o > b else f"{o:.2f} / {b:.2f}"))
    for k, r in res.items():
        L.append(f"| {k} | " + " | ".join(fmt(*r[d]) for d in DIMS) + f" | {r['_top']} |")
    L += ["", "## Across runs", "", "| dimension | runs above baseline | median [bootstrap 95% CI] | median baseline |", "|---|---|---|---|"]
    n = len(res)
    for d in DIMS:
        o = [r[d][0] for r in res.values()]; b = [r[d][1] for r in res.values()]
        k = sum(1 for x, y in zip(o, b) if x > y); lo, hi = boot_ci(o)
        L.append(f"| {d} | {k} of {n} (chance ≈ {0.05 * n:.1f}) | {np.nanmedian(o):.2f} [{lo:.2f}, {hi:.2f}] | {np.nanmedian(b):.2f} |")
    tops = Counter(r["_top"] for r in res.values())
    L += ["", "## Signatures (diagnostic, not decisive)", ""]
    if n >= 2:
        top, cnt = tops.most_common(1)[0]
        corr = [_spearman(a["_received"], b["_received"]) for a, b in itertools.combinations(res.values(), 2)]
        L.append(f"- Same member is top receiver in {cnt} of {n} runs (member {top}); mean cross-run rank correlation "
                 f"of interactions received {np.nanmean(corr):+.2f}. Recurrence of the same member across independent "
                 f"runs points to prescribed or label-induced structure when member identities are comparable across runs.")
    else:
        L.append("- Needs at least two independent runs.")
    L += ["", "## Steps 2 and 3. Stress-test and attribute", "",
          "A single condition's logs show persistence, not where it came from. Run this report on logs from "
          "matched conditions (shuffled or balanced labels, wiped histories, cut communication, reassigned roles) "
          "and compare the counts and medians above; the technical appendix gives the contrasts and decision rules.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--csv"); g.add_argument("--specimens")
    ap.add_argument("--window", type=int, default=10); ap.add_argument("--out")
    a = ap.parse_args()
    if a.csv:
        runs, src = runs_from_csv(a.csv, a.window), a.csv
    else:
        ps = sorted(glob.glob(os.path.join(a.specimens, "*.json"))) if os.path.isdir(a.specimens) else sorted(glob.glob(a.specimens))
        runs, src = runs_from_specimens(ps), a.specimens
    text = report(runs, src); print(text)
    if a.out:
        open(a.out, "w").write(text + "\n")
